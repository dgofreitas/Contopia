export function getStickerName(svgId, t) {
  const nameKey = svgId === 'rainbow-arc' ? 'rainbowArc'
    : svgId === 'double-heart' ? 'doubleHeart'
    : svgId === 'party-hat' ? 'partyHat'
    : svgId;
  return t(`cover.stickers.${nameKey}`);
}

const generateId = () => {
  if (typeof crypto !== 'undefined' && crypto.randomUUID) {
    return crypto.randomUUID();
  }
  return Math.random().toString(36).slice(2);
};

